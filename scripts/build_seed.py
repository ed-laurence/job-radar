# Structured person-name fields hold Faker names by design; the heuristic covers free text only.
NAME_FIELDS = {
    "first_name",
    "last_name",
    "target_name",
    "from_name",
    "who",
    "name",
    "display_name",
}
BAD_URL_RE = re.compile(r"linkedin\.com|seek\.com\.au", re.IGNORECASE)
PAIR_RE = re.compile(r"\b([A-Z][a-z]{1,15})\s+([A-Z][a-z]{1,20})\b")


def _faker_names() -> tuple[set[str], set[str]]:
    import importlib

    firsts: set[str] = set()
    lasts: set[str] = set()
    for loc in ["en_US", "en_AU", "en_GB", "en_IN", "en_NZ"]:
        try:
            mod = importlib.import_module(f"faker.providers.person.{loc}")
        except ImportError:
            continue
        p = mod.Provider
        for attr in ["first_names", "first_names_male", "first_names_female"]:
            firsts |= set(getattr(p, attr, ()) or ())
        lasts |= set(getattr(p, "last_names", ()) or ())
    return firsts, lasts


def _walk(obj: Any, key: str = "") -> Iterator[tuple[str, str]]:
    if isinstance(obj, dict):
        for k, v in obj.items():
            yield from _walk(v, k)
    elif isinstance(obj, list):
        for v in obj:
            yield from _walk(v, key)
    elif isinstance(obj, str):
        yield key, obj


def verify(seed_dir: Path) -> int:
    firsts, lasts = _faker_names()
    deny: list[str] = []
    dpath = Path.home() / ".config" / "jobradar" / "denylist.txt"
    if dpath.exists():
        deny = [
            ln.strip().lower()
            for ln in dpath.read_text(encoding="utf-8").splitlines()
            if ln.strip() and not ln.strip().startswith("#")
        ]
    problems: list[str] = []
    files = sorted(
        p
        for p in seed_dir.rglob("*")
        if p.is_file()
        and p.suffix in {".jsonl", ".json"}
        and "local" not in p.relative_to(seed_dir).parts
    )
    for path in files:
        rel = path.relative_to(seed_dir).as_posix()
        lines = path.read_text(encoding="utf-8").splitlines()
        records = (
            [json.loads(ln) for ln in lines if ln.strip()]
            if path.suffix == ".jsonl"
            else [json.loads("\n".join(lines))]
        )
        for i, rec in enumerate(records, start=1):
            for key, val in _walk(rec):
                where = f"{rel}:{i}:{key}"
                for m in EMAIL_RE.finditer(val):
                    dom = m.group(0).rsplit("@", 1)[1].lower()
                    if not (dom == "example.test" or dom.endswith(".example.test")):
                        problems.append(f"{where}: email outside example.test")
                for m in PHONE_RE.finditer(val):
                    s = m.group(1)
                    if sum(c.isdigit() for c in s) >= 8 and not ISO_DATEISH_RE.match(
                        s.strip()
                    ):
                        problems.append(f"{where}: phone-like number")
                if BAD_URL_RE.search(val):
                    problems.append(f"{where}: linkedin/seek URL")
                low = val.lower()
                for d in deny:
                    if d in low:
                        problems.append(f"{where}: denylisted value")
                if key not in NAME_FIELDS:
                    for m in PAIR_RE.finditer(val):
                        a, b = m.group(1), m.group(2)
                        if (
                            (a, b) not in ALLOWED_NAME_PAIRS
                            and a in firsts
                            and b in lasts
                        ):
                            problems.append(
                                f"{where}: possible person name '{a} {b[0]}.'"
                            )
    if problems:
        for p in problems[:50]:
            print("FAIL", p)
        print(f"seed verify: {len(problems)} problem(s) in {len(files)} file(s)")
        return 1
    print(f"seed verify: ok ({len(files)} files)")
    return 0


