def synth_description(
    title: str,
    company: str,
    location: str | None,
    mode: str | None,
    keywords: list[str],
    pay: dict[str, Any] | None,
    key: int,
) -> str:
    where = f" in {location}" if location else ""
    parts = [
        OPENERS[key % len(OPENERS)]
        .format(company=company, title=title, where=where)
        .replace(" a " + title, " " + article(title) + " " + title),
        MIDDLES[(key >> 4) % len(MIDDLES)],
        MODE_LINES.get(mode, MODE_LINES[None]),
    ]
    text = " ".join(parts)
    if keywords:
        text += "\n\nWhat you'll bring:\n" + "\n".join(f"- {k}" for k in keywords)
    if pay and pay.get("display"):
        text += f"\n\nPackage: {pay['display']}."
    return text


def synth_why(
    breakdown: dict[str, Any] | None, mode: str | None, location: str | None
) -> str | None:
    if not breakdown:
        return None
    bits = []
    if "skills" in breakdown:
        bits.append(f"skills {breakdown['skills']}")
    if "track_pay" in breakdown:
        bits.append(f"track and pay {breakdown['track_pay']}")
    if "location" in breakdown:
        bits.append(f"location {breakdown['location']}")
    where = ", ".join(x for x in [mode, location] if x)
    return "Score parts: " + ", ".join(bits) + (f". {where}." if where else ".")


def map_filter_reason(r: str | None) -> str | None:
    if not r:
        return None
    if r.startswith("same job as"):
        return "duplicate of an earlier listing"
    m = re.match(r"title excluded \(([^)]{1,30})\)", r)
    if m:
        return f"title excluded ({m.group(1).title()})"
    for prefix, label in [
        ("pre-screen", "pre-screen: weak fit"),
        ("ad check", "ad check: score below threshold"),
        ("title has no", "title has no data/tech/leadership keyword"),
        ("couldn't fetch", "couldn't fetch the full ad"),
    ]:
        if r.startswith(prefix):
            return label
    return "filtered"


