def _ascii(s: str) -> str:
    return re.sub(r"[^a-z]", "", s.lower()) or "x"


def write_out(
    tables: dict[str, list[dict[str, Any]]], out: Path, anchor: str, keep: bool
) -> None:
    out.mkdir(parents=True, exist_ok=True)
    files = {}
    for name in sorted(tables):
        body = "".join(dumps(r) + "\n" for r in tables[name]).encode("utf-8")
        (out / f"{name}.jsonl").write_bytes(body)
        files[f"{name}.jsonl"] = {
            "count": len(tables[name]),
            "sha256": hashlib.sha256(body).hexdigest(),
        }
    manifest = {
        "schema_version": SCHEMA_VERSION,
        "anchor": anchor,
        "synthetic": True,
        "real_companies": keep,
        "files": files,
    }
    (out / "manifest.json").write_bytes(
        (json.dumps(manifest, sort_keys=True, indent=2) + "\n").encode()
    )


