NUM_RE = re.compile(r"\$?\s*(\d{1,3}(?:,\d{3})+|\d+(?:\.\d+)?)\s*([kK])?")


def salary_band(pay: str | None) -> dict[str, Any] | None:
    if not pay:
        return None
    low = pay.lower()
    nums: list[float] = []
    for m in NUM_RE.finditer(pay):
        v = float(m.group(1).replace(",", ""))
        if m.group(2):
            v *= 1000
        nums.append(v)
    nums = [n for n in nums if n >= 20]
    if not nums:
        return (
            {"display": "Competitive", "period": None} if "competitive" in low else None
        )
    lo, hi = min(nums), max(nums)
    if re.search(r"/\s*h(ou)?r|per hour|hourly|p\.?h", low) or hi < 400:
        period, step = "hour", 10
    elif re.search(r"/\s*day|per day|daily|p\.?d\b", low) or hi < 5000:
        period, step = "day", 100
    else:
        period, step = "year", 10000
    lo_b = int(math.floor(lo / step) * step)
    hi_b = int(math.ceil(hi / step) * step)
    if hi_b == lo_b:
        hi_b += step
    if period == "year":
        disp = f"${lo_b // 1000}k–${hi_b // 1000}k per year"
    else:
        disp = f"${lo_b:,}–${hi_b:,} per {period}"
    return {
        "min": lo_b,
        "max": hi_b,
        "period": period,
        "currency": "AUD",
        "display": disp,
    }


