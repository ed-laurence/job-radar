def scrub(text: str) -> str:
    """Remove emails, URLs and phone-like numbers from short source strings (titles, places)."""
    text = EMAIL_RE.sub("", text)
    text = URL_RE.sub("", text)
    text = PHONE_RE.sub(
        lambda m: "" if sum(c.isdigit() for c in m.group(1)) >= 8 else m.group(0), text
    )
    return re.sub(r"\s{2,}", " ", text).strip(" -|,")


def extract_keywords(description: str | None, title: str, limit: int = 8) -> list[str]:
    text = scrub(f"{title}\n{description or ''}")
    found: list[str] = []
    for skill, rx in _SKILL_RES:
        alias = _SKILL_ALIASES.get(skill)
        if skill in {"Go", "R"}:
            hit = bool(alias and alias.search(text))
        else:
            hit = bool(rx.search(text) or (alias and alias.search(text)))
        if hit and skill.lower() not in STOP_WORDS:
            found.append(skill)
        if len(found) >= limit:
            break
    return found


TITLE_SPLIT_RE = re.compile(r"\s*[|@•·]\s*|\s+[-–—:]\s+|\s+at\s+|(\([^)]*\))")
TITLE_TOKEN_RE = re.compile(r"[A-Za-z][A-Za-z.&+#'-]*")
# A title word is kept only if it shows up in the titles of at least this many different
# companies. Employer names, people (e.g. a named judge) and small suburbs are rare, so they drop.
COMMON_MIN_COMPANIES = 5


def common_title_words(rows: Iterable[sqlite3.Row]) -> set[str]:
    seen: dict[str, set[str]] = defaultdict(set)
    for r in rows:
        co = norm_company(r["company"]) or f"row{r['id']}"
        for tok in TITLE_TOKEN_RE.findall(r["title"] or ""):
            seen[tok.lower()].add(co)
    common = {t for t, cos in seen.items() if len(cos) >= COMMON_MIN_COMPANIES}
    return common | {s.lower() for s in SKILLS}


def clean_title(raw: str, common: set[str]) -> str:
    """Keep only title segments made entirely of words common across many employers."""
    text = scrub(raw)
    # Anything after "@" or " at " names the employer.
    text = re.split(r"\s@\s|\s+at\s+(?=[A-Z])", text, maxsplit=1)[0]
    segs = [
        x.strip(" -–—,/") for x in TITLE_SPLIT_RE.split(text) if x and x.strip(" -–—,/")
    ]
    kept: list[str] = []
    for seg in segs:
        toks = TITLE_TOKEN_RE.findall(seg.strip("()"))
        if (
            toks
            and all(t.lower() in common for t in toks)
            and not re.search(r"\d{2,}", seg)
        ):
            kept.append(seg)
    if not kept or kept[0].startswith("("):
        # The main segment was dropped: rebuild it from its common words only.
        for seg in (x for x in segs if not x.startswith("(")):
            words = [t for t in TITLE_TOKEN_RE.findall(seg) if t.lower() in common]
            if words:
                kept.insert(0, " ".join(words))
                break
    if not kept or kept[0].startswith("("):
        return "Untitled role"
    out = kept[0]
    for seg in kept[1:]:
        out += f" {seg}" if seg.startswith("(") else f" - {seg}"
    return out


def article(word: str) -> str:
    return "an" if word[:1].lower() in "aeiou" else "a"


