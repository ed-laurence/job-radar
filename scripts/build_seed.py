def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument(
        "--source", type=Path, help="job-seeker jobradar.db (opened read-only)"
    )
    ap.add_argument("--out", type=Path, default=Path("seed"))
    ap.add_argument(
        "--anchor", default=DEFAULT_ANCHOR, help="ISO time the newest record shifts to"
    )
    ap.add_argument(
        "--salt",
        default=None,
        help=(
            "secret hash salt for ids and fake company names. Default: $JOBRADAR_SEED_SALT, "
            "else ~/.config/jobradar/seed_salt (created with a random value on first run). "
            "Never commit it: a known salt lets anyone map real employers to fake names."
        ),
    )
    ap.add_argument(
        "--keep-companies",
        action="store_true",
        help="LOCAL ONLY: keep real company names; writes to <out>/local/",
    )
    ap.add_argument(
        "--verify", action="store_true", help="scan the seed dir for PII and exit"
    )
    a = ap.parse_args(argv)
    if a.verify:
        return verify(a.out)
    if not a.source or not a.source.exists():
        ap.error("--source must point to an existing database")
    anchor = parse_ts(a.anchor)
    if anchor is None:
        ap.error("--anchor must be an ISO timestamp")
    out = a.out / "local" if a.keep_companies else a.out
    salt = resolve_salt(a.salt)
    con = open_ro(a.source)
    try:
        tables = Builder(con, anchor, salt, a.keep_companies).build()
    finally:
        con.close()
    write_out(tables, out, fmt(anchor) or a.anchor, a.keep_companies)
    for name in sorted(tables):
        print(f"{name}: {len(tables[name])}")
    print(f"wrote {out}")
    return 0


