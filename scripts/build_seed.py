def resolve_salt(cli_salt: str | None) -> str:
    """Secret salt: CLI > env > local config file (created on first run). Never in the repo."""
    if cli_salt:
        return cli_salt
    env_salt = os.environ.get("JOBRADAR_SEED_SALT")
