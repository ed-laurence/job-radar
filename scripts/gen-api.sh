#!/usr/bin/env bash
# Generate code from the OpenAPI contract (api/openapi.yaml).
#
#   scripts/gen-api.sh            regenerate in place
#   scripts/gen-api.sh --check    regenerate into a temp dir and fail if it differs from disk
#   --only=web | --only=backend   limit either mode to one side (default: both)
#
# Outputs (never hand-edit these):
#   backend/src/app/generated/models.py      Pydantic v2 models  (datamodel-code-generator)
#   web/src/lib/api/generated/schema.d.ts    TypeScript types    (openapi-typescript)
#   web/src/lib/api/generated/client.ts      typed fetch client  (openapi-fetch wrapper)
#   web/src/lib/api/generated/labels.ts      enum values + display labels from `x-enum-labels`
#
# A side is skipped (with a message) while backend/ or web/ doesn't exist yet.
# Exit codes: 0 ok / in sync, 1 out of sync or generator failure, 3 nothing to do (no spec).
# Tool versions are pinned in scripts/lib/common.sh, and output is normalised to LF,
# so the result is byte-identical on every machine.
set -euo pipefail
JR_SCRIPT=gen-api
# shellcheck source=lib/common.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib/common.sh"

MODE=write
ONLY=""
for arg in "$@"; do
  case "$arg" in
    --check) MODE=check ;;
    --only=web|--only=backend) ONLY="${arg#--only=}" ;;
    -h|--help) sed -n '2,18p' "$0"; exit 0 ;;
    *) die "unknown argument: $arg" ;;
  esac
done

cd "$JR_ROOT"
SPEC="api/openapi.yaml"
BACKEND_OUT="backend/src/app/generated"
WEB_OUT="web/src/lib/api/generated"
HEADER="# GENERATED by scripts/gen-api.sh from api/openapi.yaml. DO NOT EDIT."

if [[ ! -f "$SPEC" ]]; then
  log "SKIP: $SPEC does not exist yet"
  exit 3
fi

to_lf() { local f; for f in "$@"; do sed -i 's/\r$//' "$f"; done; }

gen_backend() { # $1 = output dir
  local out="$1"
  mkdir -p "$out"
  have uv || die "uv is required for backend generation"
  uv run --no-project --quiet --python "$JR_PYTHON_VERSION" \
    --with "datamodel-code-generator==${JR_DATAMODEL_CODEGEN_VERSION}" \
    --with "ruff==${JR_RUFF_VERSION}" \
    datamodel-codegen \
      --input "$SPEC" --input-file-type openapi \
      --output "$(native_path "$out/models.py")" \
      --output-model-type pydantic_v2.BaseModel \
      --target-python-version 3.12 \
      --disable-timestamp \
      --use-standard-collections --use-union-operator --use-double-quotes \
      --field-constraints --use-schema-description \
      --type-mappings "string+email=string" \
      --formatters ruff-format ruff-check \
      --custom-file-header "$HEADER"
  printf '%s\n' "$HEADER" '"""Models generated from api/openapi.yaml."""' > "$out/__init__.py"
  to_lf "$out/models.py" "$out/__init__.py"
}

gen_web() { # $1 = output dir
  local out="$1"
  mkdir -p "$out"
  have npx || die "npx (Node 20+) is required for web generation"
  npx -y "openapi-typescript@${JR_OPENAPI_TS_VERSION}" "$SPEC" \
    -o "$(native_path "$out/schema.d.ts")" >/dev/null
  cat > "$out/client.ts" <<'EOF'
// GENERATED by scripts/gen-api.sh from api/openapi.yaml. DO NOT EDIT.
import createClient, { type ClientOptions } from "openapi-fetch";
import type { components, operations, paths } from "./schema";

export type { components, operations, paths };
export type Schemas = components["schemas"];

/** Typed client for the Job Radar API. Requires the `openapi-fetch` dependency. */
export function createApiClient(options: ClientOptions = {}) {
  return createClient<paths>(options);
}
EOF
  have node || die "node (20+) is required for web generation"
  node - "$SPEC" "$(native_path "$out/labels.ts")" <<'NODE'
// Emits enum values and their `x-enum-labels` for every component schema that declares them.
// The spec is block-style YAML written by a dumper; this reads exactly that shape (no YAML
// dependency) and fails on anything else rather than guessing.
const fs = require("node:fs");
const [specPath, outPath] = process.argv.slice(2);
const fail = (msg) => {
  process.stderr.write(`[gen-api] error: labels: ${msg}\n`);
  process.exit(1);
};
const lines = fs.readFileSync(specPath, "utf8").replace(/\r/g, "").split("\n");
const indentOf = (l) => l.length - l.trimStart().length;
const blockEnd = (from, maxIndent) => {
  let k = from;
  while (k < lines.length && (lines[k].trim() === "" || indentOf(lines[k]) > maxIndent)) k++;
  return k;
};

function scalar(raw, where) {
  const v = raw.trim();
  if (v.startsWith("'")) {
    if (!v.endsWith("'") || v.length < 2) fail(`${where}: unterminated quote: ${v}`);
    return v.slice(1, -1).replace(/''/g, "'");
  }
  if (v.startsWith('"')) {
    try {
      return JSON.parse(v);
    } catch {
      fail(`${where}: unsupported double-quoted scalar: ${v}`);
    }
  }
  if (v === "" || /\s#/.test(v) || /^[&*!|>%@`{[]/.test(v)) fail(`${where}: unsupported scalar: ${v}`);
  if (/^(true|false|null|~|yes|no|on|off|[-+]?[0-9][0-9_.eE+-]*)$/i.test(v)) {
    fail(`${where}: "${v}" is not a plain string; quote it in the spec`);
  }
  return v;
}

function list(start, end, key, where) {
  const at = lines.slice(start, end).findIndex((l) => l.trimEnd() === `      ${key}:`);
  if (at < 0) return null;
  const items = [];
  for (let k = start + at + 1; k < end; k++) {
    const m = /^ {6}(?: {2})?- (.*)$/.exec(lines[k]);
    if (!m) break;
    items.push(scalar(m[1], `${where}.${key}[${items.length}]`));
  }
  if (items.length === 0) fail(`${where}.${key}: expected a block list`);
  return items;
}

const components = lines.indexOf("components:");
if (components < 0) fail("no top-level `components:`");
const componentsEnd = blockEnd(components + 1, 0);
const schemas = lines.indexOf("  schemas:", components);
if (schemas < 0 || schemas > componentsEnd) fail("no `components.schemas`");
const schemasEnd = blockEnd(schemas + 1, 2);

const found = [];
for (let k = schemas + 1; k < schemasEnd; k++) {
  const m = /^ {4}([A-Za-z0-9_.-]+):\s*$/.exec(lines[k]);
  if (!m) continue;
  const name = m[1];
  const end = blockEnd(k + 1, 4);
  const labels = list(k + 1, end, "x-enum-labels", name);
  if (labels) {
    const values = list(k + 1, end, "enum", name);
    if (!values) fail(`${name}: x-enum-labels without an enum`);
    if (values.length !== labels.length) {
      fail(`${name}: ${values.length} enum values but ${labels.length} labels`);
    }
    if (new Set(values).size !== values.length) fail(`${name}: duplicate enum values`);
    found.push({ name, values, labels });
  }
  k = end - 1;
}
const declared = lines.filter((l) => /^\s*(- )?x-enum-labels\s*:/.test(l)).length;
if (declared !== found.length) {
  fail(`${declared} x-enum-labels in the spec, ${found.length} read; only block lists on top-level component schemas are supported`);
}

found.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
const q = JSON.stringify;
const out = [
  "// GENERATED by scripts/gen-api.sh from api/openapi.yaml. DO NOT EDIT.",
  'import type { components } from "./schema";',
  "",
  'type Schemas = components["schemas"];',
  "",
  "/** Schemas whose enum carries display labels (`x-enum-labels`) in the spec. */",
  `export type LabelledEnum = ${found.length ? found.map((f) => q(f.name)).join(" | ") : "never"};`,
  "",
  "/** Enum values in spec order. */",
  "export const enumValues = {",
  ...found.flatMap((f) => [`  ${q(f.name)}: [`, ...f.values.map((v) => `    ${q(v)},`), "  ],"]),
  "} as const satisfies { readonly [K in LabelledEnum]: readonly Schemas[K][] };",
  "",
  "/** Display label per enum value, from `x-enum-labels`. */",
  "export const enumLabels = {",
  ...found.flatMap((f) => [
    `  ${q(f.name)}: {`,
    ...f.values.map((v, i) => `    ${q(v)}: ${q(f.labels[i])},`),
    "  },",
  ]),
  "} as const satisfies { readonly [K in LabelledEnum]: Readonly<Record<Schemas[K], string>> };",
  "",
];
fs.writeFileSync(outPath, out.join("\n"));
NODE
  to_lf "$out/schema.d.ts" "$out/client.ts" "$out/labels.ts"
}

sides=()
[[ -d backend ]] && sides+=(backend) || log "SKIP backend: backend/ does not exist yet"
[[ -d web ]] && sides+=(web) || log "SKIP web: web/ does not exist yet"
if [[ -n "$ONLY" ]]; then
  kept=()
  for s in "${sides[@]}"; do [[ $s == "$ONLY" ]] && kept+=("$s"); done
  sides=("${kept[@]}")
fi
if [[ ${#sides[@]} -eq 0 ]]; then
  log "nothing to generate"
  exit 3
fi

if [[ "$MODE" == write ]]; then
  for s in "${sides[@]}"; do
    if [[ $s == backend ]]; then
      tmp="$(mktemp -d)"; gen_backend "$tmp"
      rm -rf "$BACKEND_OUT"; mkdir -p "$BACKEND_OUT"; cp "$tmp"/* "$BACKEND_OUT"/; rm -rf "$tmp"
      ok "backend models -> $BACKEND_OUT"
    else
      tmp="$(mktemp -d)"; gen_web "$tmp"
      rm -rf "$WEB_OUT"; mkdir -p "$WEB_OUT"; cp "$tmp"/* "$WEB_OUT"/; rm -rf "$tmp"
      ok "web types + client + labels -> $WEB_OUT"
    fi
  done
  exit 0
fi

# --check: generate into a scratch tree and compare with what's on disk.
scratch="$(mktemp -d)"
trap 'rm -rf "$scratch"' EXIT
drift=0
for s in "${sides[@]}"; do
  if [[ $s == backend ]]; then dest="$BACKEND_OUT"; gen_backend "$scratch/backend"; got="$scratch/backend"
  else dest="$WEB_OUT"; gen_web "$scratch/web"; got="$scratch/web"; fi
  if [[ ! -d "$dest" ]]; then
    warn "$dest is missing; run scripts/gen-api.sh"; drift=1; continue
  fi
  if ! diff -r -q -x __pycache__ -x '*.pyc' "$got" "$dest" >&2; then
    warn "$dest is out of sync with $SPEC; run scripts/gen-api.sh"; drift=1
  else
    ok "$dest in sync"
  fi
done
exit "$drift"
